# Keywords are reserved words that have special meaning in Python and cannot be used as variable names.

# Examples of common key words:

# and              def        assert      break       class
# continue         False      del         elif        else
# except           if         finally     for         from
# global           None       import      in          is
# lambda           raise      nonlocal    not         or
# pass             with       return      True        try
# while            as         yield
    
# IF we use any of the above words as variable, Python will automatically give us error.
# Tip: Use help("Keywords") in Python shell to list all current keywords.

